export function lendingChainLogo(chainId: string): string | null {
  return LENDING_CHAIN_LOGOS[chainId] ?? null;
}

export function lendingVenueLogo(venueId: string): string | null {
  if (venueId.startsWith("kamino")) return LENDING_VENUE_LOGOS.kamino ?? null;
  if (venueId.startsWith("jupiter")) return LENDING_VENUE_LOGOS.jupiter ?? null;
  if (venueId.startsWith("aave")) return LENDING_VENUE_LOGOS.aave ?? null;
  if (venueId.startsWith("morpho")) return LENDING_VENUE_LOGOS.morpho ?? null;
  if (venueId.startsWith("venus")) return LENDING_VENUE_LOGOS.venus ?? null;
  if (venueId.startsWith("lista")) return LENDING_VENUE_LOGOS.lista ?? null;
  if (venueId.startsWith("frankencoin")) return LENDING_VENUE_LOGOS.frankencoin ?? null;
  if (venueId.startsWith("euler")) return LENDING_VENUE_LOGOS.euler ?? null;
  return null;
}

export function lendingStockLogo(symbolOrAddress: string, ticker: string): string | null {
  return TICKER_LOGOS[ticker] ?? TOKEN_LOGOS[symbolOrAddress] ?? TOKEN_LOGOS[symbolOrAddress.toLowerCase()] ?? null;
}

